function inGeist(codePoint: number): boolean {
  let lo = 0;
  let hi = GEIST_RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const range = GEIST_RANGES[mid];
    if (range === undefined) break;
    const [start, end] = range;
    if (codePoint < start) hi = mid - 1;
    else if (codePoint > end) lo = mid + 1;
    else return true;
  }
  return false;
}

/** A character the card draws as it is: one Geist has, and not one the
 * renderer would treat as an emoji even so (☺). */
function drawable(char: string): boolean {
  const codePoint = char.codePointAt(0) ?? 0;
  if (codePoint >= 0x2000 && /\p{Extended_Pictographic}/u.test(char)) return false;
  return inGeist(codePoint);
}

/** `text` with only characters the card's font has: an accented letter
 * Geist lacks drops to its base letter ("Ǹ" to "N"),
 * anything else (an emoji, a script Geist has no glyphs for) is left out,
 * and the spaces around it close up. */
export function renderableText(text: string): string {
  let out = '';
  for (const char of text.normalize('NFC')) {
    if (/\s/u.test(char)) {
      out += ' ';
    } else if (drawable(char)) {
      out += char;
    } else {
      const base = char.normalize('NFD').replace(/\p{M}/gu, '');
      if (base !== char && base !== '' && Array.from(base).every(drawable)) out += base;
    }
  }
  return out.replace(/ {2,}/g, ' ').trim();
}
